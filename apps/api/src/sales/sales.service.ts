import { BadRequestException, ConflictException, ForbiddenException, Injectable, NotFoundException } from '@nestjs/common';
import { Type } from 'class-transformer';
import { IsArray, IsBoolean, IsEnum, IsInt, IsISO8601, IsNumber, IsOptional, IsPositive, IsString, IsUUID, Min, ValidateNested } from 'class-validator';
import { BusinessLineCode, Prisma, ReturnReason, SaleType, UnitName } from '@prisma/client';
import { PrismaService } from '../prisma.service.js';
import { AuditService } from '../audit/audit.module.js';
import { dayOf } from '../common/dates.js';
import type { AuthUser } from '../common/decorators.js';
import { StockService, type Tx } from '../stock/stock.service.js';

const D = Prisma.Decimal;
type Dec = Prisma.Decimal;

export class SaleLineDto {
  @IsUUID() productId: string;
  @IsEnum(UnitName) unitName: UnitName;
  @IsNumber({ maxDecimalPlaces: 3 }) @IsPositive() qty: number;
  /** Omit to use the customer's fixed rate, then the list price. Any other value needs RATE_EDIT. */
  @IsOptional() @IsNumber({ maxDecimalPlaces: 2 }) @Min(0) rate?: number;
}

export class SaleReturnLineDto extends SaleLineDto {
  @IsEnum(ReturnReason) reason: ReturnReason;
}

export class EmptiesCollectedDto {
  @IsUUID() productId: string;
  @IsInt() @Min(1) qty: number;
}

export class SaleDto {
  /** Generated by the client; sending the same bill twice creates it once. */
  @IsOptional() @IsUUID() clientId?: string;
  @IsEnum(SaleType) saleType: SaleType;
  @IsOptional() @IsUUID() customerId?: string;
  @IsUUID() locationId: string;
  @IsOptional() @IsUUID() salesmanId?: string;
  @IsOptional() @IsISO8601() date?: string;
  @IsOptional() @IsArray() @ValidateNested({ each: true }) @Type(() => SaleLineDto) items?: SaleLineDto[];
  @IsOptional() @IsArray() @ValidateNested({ each: true }) @Type(() => SaleReturnLineDto) returns?: SaleReturnLineDto[];
  @IsOptional() @IsNumber({ maxDecimalPlaces: 2 }) @Min(0) paidNow?: number;
  @IsOptional() @IsString() method?: string;
  @IsOptional() @IsArray() @ValidateNested({ each: true }) @Type(() => EmptiesCollectedDto) emptiesCollected?: EmptiesCollectedDto[];
  /** Save even though the credit limit would be crossed. Needs CREDIT_OVERRIDE. */
  @IsOptional() @IsBoolean() overrideCredit?: boolean;
  @IsOptional() @IsString() note?: string;
}

interface Line {
  productId: string;
  productName: string;
  unitName: UnitName;
  qty: Dec;
  qtyBase: Dec;
  rate: Dec;
  amount: Dec;
  unitCostBase: Dec | null;
  returnableEmpty: boolean;
  reason?: ReturnReason;
}

export interface Plan {
  businessLine: BusinessLineCode;
  customer: { id: string; name: string; type: 'CASH' | 'CREDIT'; creditLimit: Dec | null } | null;
  items: Line[];
  returns: Line[];
  gross: Dec;
  returnsCredit: Dec;
  net: Dec;
  paid: Dec;
  previousBalance: Dec;
  newBalance: Dec;
  credit: { limit: Dec | null; available: Dec | null; blocked: string | null };
  empties: { productId: string; productName: string; given: number; collected: number; heldAfter: number }[];
  shortages: string[];
}

@Injectable()
export class SalesService {
  constructor(private prisma: PrismaService, private stock: StockService, private audit: AuditService) {}

  // ---------------------------------------------------------------- balances

  /** What the customer owes: opening balance plus every ledger entry. Negative = they are in credit. */
  async balance(tx: Tx, customerId: string): Promise<Dec> {
    const [c, sum] = await Promise.all([
      tx.customer.findUniqueOrThrow({ where: { id: customerId }, select: { openingBalance: true } }),
      tx.customerLedger.aggregate({ where: { customerId }, _sum: { amount: true } }),
    ]);
    return c.openingBalance.plus(sum._sum.amount ?? 0);
  }

  /** Serialises everything that changes one customer's balance so the previous-balance snapshot is exact. */
  private lockCustomer(tx: Tx, customerId: string) {
    return tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtext(${'customer:' + customerId}))`;
  }

  private async held(tx: Tx, customerId: string, productId: string): Promise<number> {
    const r = await tx.emptiesLedger.aggregate({ where: { customerId, productId }, _sum: { qtyOut: true, qtyIn: true } });
    return (r._sum.qtyOut ?? 0) - (r._sum.qtyIn ?? 0);
  }

  // -------------------------------------------------------------------- plan

  /** All the rules, with no writes. Used by both preview and save. */
  async plan(tx: Tx, dto: SaleDto, user: AuthUser, opts: { preview: boolean }): Promise<Plan> {
    const itemDtos = dto.items ?? [];
    const returnDtos = dto.returns ?? [];
    if (!itemDtos.length && !returnDtos.length) throw new BadRequestException('Add at least one item or return');

    // ---- where and who
    if (dto.saleType === 'COUNTER') await this.stock.requireLocation(tx, dto.locationId, ['SHOP', 'GODOWN']);
    else await this.stock.requireLocation(tx, dto.locationId, ['VEHICLE']);
    if (dto.saleType === 'DELIVERY' && !dto.salesmanId) throw new BadRequestException('A delivery needs a salesman');
    if (dto.salesmanId) {
      const e = await tx.employee.findUnique({ where: { id: dto.salesmanId } });
      if (!e?.isActive) throw new BadRequestException('Unknown or inactive salesman');
    }
    if (!dto.customerId && dto.saleType === 'DELIVERY') throw new BadRequestException('A delivery needs a customer');

    const customer = dto.customerId ? await tx.customer.findUnique({ where: { id: dto.customerId } }) : null;
    if (dto.customerId && !customer?.isActive) throw new BadRequestException('Unknown or inactive customer');

    // ---- lines
    const productIds = [...new Set([...itemDtos, ...returnDtos].map((l) => l.productId))];
    const products = await tx.product.findMany({
      where: { id: { in: productIds } },
      include: { cost: true, category: { select: { businessLine: { select: { code: true } } } } },
    });
    const [custRates, listPrices] = await Promise.all([
      customer ? tx.customerRate.findMany({ where: { customerId: customer.id, productId: { in: productIds } } }) : [],
      tx.productPrice.findMany({ where: { productId: { in: productIds } } }),
    ]);

    const resolve = async (l: SaleLineDto): Promise<Line> => {
      const p = products.find((x) => x.id === l.productId);
      if (!p?.isActive) throw new BadRequestException('Unknown or inactive product');
      const { qtyBase } = await this.stock.toBase(tx, l.productId, l.unitName, l.qty);
      const fixed = custRates.find((r) => r.productId === l.productId && r.unitName === l.unitName)?.rate;
      const list = listPrices.find((r) => r.productId === l.productId && r.unitName === l.unitName)?.rate;
      const standard = fixed ?? list ?? null;
      let rate: Dec;
      if (l.rate == null) {
        if (!standard) {
          if (!user.permissions.includes('RATE_EDIT')) throw new ForbiddenException(`No rate is set for ${p.name} (${l.unitName}); ask someone who can set rates`);
          throw new BadRequestException(`No rate is set for ${p.name} (${l.unitName}); enter one`);
        }
        rate = standard;
      } else {
        rate = new D(l.rate);
        if ((!standard || !rate.eq(standard)) && !user.permissions.includes('RATE_EDIT')) {
          throw new ForbiddenException(`You are not allowed to change the rate of ${p.name}`);
        }
      }
      return {
        productId: p.id,
        productName: p.name,
        unitName: l.unitName,
        qty: new D(l.qty),
        qtyBase,
        rate,
        amount: this.stock.money(new D(l.qty).mul(rate)),
        unitCostBase: p.cost?.latestUnitCostBase ?? null,
        returnableEmpty: p.returnableEmpty,
      };
    };
    const items = await Promise.all(itemDtos.map(resolve));
    const returns = await Promise.all(returnDtos.map(async (l) => ({ ...(await resolve(l)), reason: l.reason })));

    const lines = new Set(products.map((p) => p.category.businessLine.code));
    if (lines.size > 1) throw new BadRequestException('A bill can hold bottles or rice, not both. Make two bills.');
    const businessLine = [...lines][0];

    // ---- money
    const gross = items.reduce((s, l) => s.plus(l.amount), new D(0));
    const returnsCredit = returns.reduce((s, l) => s.plus(l.amount), new D(0));
    const net = gross.minus(returnsCredit);
    const cashLike = !customer || customer.type === 'CASH';
    const paid = new D(dto.paidNow ?? (cashLike ? D.max(net, 0) : 0));
    if (net.isNegative() && paid.gt(0)) throw new BadRequestException('A bill that credits the customer cannot also take payment');
    if (!customer && !paid.eq(net)) throw new BadRequestException('A sale without a customer must be paid in full');

    const previousBalance = customer ? await this.balance(tx, customer.id) : new D(0);
    const newBalance = previousBalance.plus(net).minus(paid);

    // ---- credit rules
    const unpaid = net.minus(paid);
    let blocked: string | null = null;
    if (customer && unpaid.gt(0)) {
      if (customer.type === 'CASH') blocked = 'CASH_CUSTOMER_UNPAID: a cash customer must pay in full';
      else if (customer.creditLimit && newBalance.gt(customer.creditLimit)) {
        blocked = `CREDIT_LIMIT_EXCEEDED: balance would be ${newBalance} against a limit of ${customer.creditLimit}`;
      }
    }
    if (blocked && !opts.preview) {
      if (!dto.overrideCredit) throw new BadRequestException(blocked);
      if (!user.permissions.includes('CREDIT_OVERRIDE')) throw new ForbiddenException('You are not allowed to override the credit limit');
    }

    // ---- empties
    const empties: Plan['empties'] = [];
    if (customer) {
      const given = new Map<string, number>();
      for (const l of items.filter((x) => x.returnableEmpty)) given.set(l.productId, (given.get(l.productId) ?? 0) + Math.round(Number(l.qtyBase)));
      const collected = new Map<string, number>();
      for (const c of dto.emptiesCollected ?? []) {
        const p = await tx.product.findUnique({ where: { id: c.productId } });
        if (!p?.returnableEmpty) throw new BadRequestException('That product has no returnable empties');
        collected.set(c.productId, (collected.get(c.productId) ?? 0) + c.qty);
      }
      for (const pid of new Set([...given.keys(), ...collected.keys()])) {
        const before = await this.held(tx, customer.id, pid);
        const g = given.get(pid) ?? 0;
        const c = collected.get(pid) ?? 0;
        const name = products.find((x) => x.id === pid)?.name ?? (await tx.product.findUniqueOrThrow({ where: { id: pid } })).name;
        empties.push({ productId: pid, productName: name, given: g, collected: c, heldAfter: before + g - c });
      }
    } else if (dto.emptiesCollected?.length) {
      throw new BadRequestException('Empties are tracked per customer');
    }

    // ---- stock (preview only; saving enforces it atomically)
    const shortages: string[] = [];
    if (opts.preview) {
      const need = new Map<string, Dec>();
      for (const l of items) need.set(l.productId, (need.get(l.productId) ?? new D(0)).plus(l.qtyBase));
      for (const [pid, qty] of need) {
        const have = await this.stock.onHand(tx, pid, dto.locationId);
        if (have.lt(qty)) shortages.push(`${items.find((x) => x.productId === pid)!.productName}: have ${have}, need ${qty}`);
      }
    }

    return {
      businessLine,
      customer: customer ? { id: customer.id, name: customer.name, type: customer.type, creditLimit: customer.creditLimit } : null,
      items, returns, gross, returnsCredit, net, paid, previousBalance, newBalance,
      credit: {
        limit: customer?.creditLimit ?? null,
        available: customer?.creditLimit ? customer.creditLimit.minus(newBalance) : null,
        blocked,
      },
      empties, shortages,
    };
  }

  preview(dto: SaleDto, user: AuthUser) {
    return this.prisma.$transaction((tx) => this.plan(tx, dto, user, { preview: true }));
  }

  // ------------------------------------------------------------------ create

  async create(dto: SaleDto, user: AuthUser) {
    if (dto.clientId) {
      const existing = await this.prisma.sale.findUnique({ where: { clientId: dto.clientId }, select: { id: true } });
      if (existing) return this.view(existing.id);
    }
    let id: string;
    try {
      id = await this.prisma.$transaction(async (tx) => {
        if (dto.customerId) await this.lockCustomer(tx, dto.customerId);
        const plan = await this.plan(tx, dto, user, { preview: false });
        const date = dayOf(dto.date);
        const billNo = await this.stock.nextNo(tx, `SALE_${plan.businessLine}`, plan.businessLine === 'BOTTLES' ? 'BTL' : 'RIC');

        const sale = await tx.sale.create({
          data: {
            billNo, clientId: dto.clientId, businessLine: plan.businessLine, saleType: dto.saleType,
            customerId: plan.customer?.id, locationId: dto.locationId, salesmanId: dto.salesmanId, date,
            gross: plan.gross, returnsCredit: plan.returnsCredit, net: plan.net, paidNow: plan.paid,
            previousBalance: plan.previousBalance, newBalance: plan.newBalance, note: dto.note,
            empties: plan.empties, createdById: user.id,
            items: {
              create: plan.items.map((l) => ({
                productId: l.productId, unitName: l.unitName, qty: l.qty, qtyBase: l.qtyBase, rate: l.rate,
                lineTotal: l.amount, unitCostBase: l.unitCostBase,
              })),
            },
            returns: {
              create: plan.returns.map((l) => ({
                productId: l.productId, unitName: l.unitName, qty: l.qty, qtyBase: l.qtyBase, rate: l.rate,
                creditAmount: l.amount, reason: l.reason!,
              })),
            },
          },
        });

        // Stock: out for items, damaged stock in for returns. Product order keeps lock order stable.
        for (const l of [...plan.items].sort((a, b) => a.productId.localeCompare(b.productId))) {
          await this.stock.move(tx, {
            productId: l.productId, locationId: dto.locationId, qtyBase: l.qtyBase.neg(), type: 'SALE',
            refType: 'SALE', refId: sale.id, userId: user.id,
          });
        }
        for (const l of plan.returns) {
          await this.stock.move(tx, {
            productId: l.productId, locationId: dto.locationId, qtyBase: l.qtyBase, status: 'DAMAGED', type: 'SALE_RETURN',
            refType: 'SALE', refId: sale.id, userId: user.id, note: l.reason,
          });
        }

        if (plan.customer) {
          const customerId = plan.customer.id;
          if (!plan.net.isZero()) {
            await tx.customerLedger.create({
              data: { customerId, date, amount: plan.net, refType: 'SALE', refId: sale.id, note: billNo, createdById: user.id },
            });
          }
          if (plan.paid.gt(0)) {
            const receiptNo = await this.stock.nextNo(tx, 'RECEIPT', 'RCP');
            const payment = await tx.payment.create({
              data: {
                receiptNo, customerId, saleId: sale.id, amount: plan.paid, method: dto.method ?? 'CASH', date,
                previousBalance: plan.previousBalance.plus(plan.net), newBalance: plan.newBalance,
                note: `With ${billNo}`, createdById: user.id,
              },
            });
            await tx.customerLedger.create({
              data: { customerId, date, amount: plan.paid.neg(), refType: 'PAYMENT', refId: payment.id, note: receiptNo, createdById: user.id },
            });
          }
          for (const e of plan.empties) {
            await tx.emptiesLedger.create({
              data: { customerId, productId: e.productId, qtyOut: e.given, qtyIn: e.collected, saleId: sale.id, createdById: user.id },
            });
          }
        }
        if (plan.credit.blocked) {
          await tx.auditLog.create({
            data: { userId: user.id, action: 'CREDIT_OVERRIDE', entity: 'Sale', entityId: sale.id, afterJson: { reason: plan.credit.blocked } },
          });
        }
        return sale.id;
      }, { timeout: 15000 });
    } catch (e) {
      // Two requests with the same clientId raced: the loser just returns the winner's bill.
      if (dto.clientId && e instanceof Prisma.PrismaClientKnownRequestError && e.code === 'P2002') {
        const existing = await this.prisma.sale.findUnique({ where: { clientId: dto.clientId }, select: { id: true } });
        if (existing) return this.view(existing.id);
      }
      throw e;
    }
    const bill = await this.view(id);
    await this.audit.log(user.id, 'CREATE', 'Sale', id, undefined, { billNo: bill.billNo, net: bill.net });
    return bill;
  }

  // ------------------------------------------------------------------ cancel

  async cancel(id: string, user: AuthUser) {
    await this.prisma.$transaction(async (tx) => {
      const sale = await tx.sale.findUnique({ where: { id }, include: { items: true, returns: true, payments: true } });
      if (!sale) throw new NotFoundException();
      if (sale.status === 'CANCELLED') throw new ConflictException('Already cancelled');
      if (sale.customerId) await this.lockCustomer(tx, sale.customerId);

      for (const it of [...sale.items].sort((a, b) => a.productId.localeCompare(b.productId))) {
        await this.stock.move(tx, {
          productId: it.productId, locationId: sale.locationId, qtyBase: it.qtyBase, type: 'SALE_CANCEL',
          refType: 'SALE', refId: sale.id, userId: user.id,
        });
      }
      for (const r of sale.returns) {
        await this.stock.move(tx, {
          productId: r.productId, locationId: sale.locationId, qtyBase: r.qtyBase.neg(), status: 'DAMAGED', type: 'SALE_CANCEL',
          refType: 'SALE', refId: sale.id, userId: user.id,
        });
      }
      const today = dayOf();
      if (sale.customerId) {
        if (!sale.net.isZero()) {
          await tx.customerLedger.create({
            data: { customerId: sale.customerId, date: today, amount: sale.net.neg(), refType: 'SALE_CANCEL', refId: sale.id, note: `Cancel ${sale.billNo}`, createdById: user.id },
          });
        }
        for (const p of sale.payments.filter((x) => x.status === 'ACTIVE')) {
          await tx.payment.update({ where: { id: p.id }, data: { status: 'CANCELLED' } });
          await tx.customerLedger.create({
            data: { customerId: sale.customerId, date: today, amount: p.amount, refType: 'PAYMENT_CANCEL', refId: p.id, note: `Cancel ${p.receiptNo}`, createdById: user.id },
          });
        }
        const rows = await tx.emptiesLedger.findMany({ where: { saleId: sale.id } });
        for (const r of rows) {
          await tx.emptiesLedger.create({
            data: { customerId: r.customerId, productId: r.productId, qtyOut: -r.qtyOut, qtyIn: -r.qtyIn, saleId: sale.id, createdById: user.id },
          });
        }
      }
      await tx.sale.update({ where: { id }, data: { status: 'CANCELLED', cancelledById: user.id, cancelledAt: new Date() } });
    }, { timeout: 15000 });
    await this.audit.log(user.id, 'CANCEL', 'Sale', id);
    return this.view(id);
  }

  // -------------------------------------------------------------------- view

  /** Everything a printed bill needs. */
  async view(id: string) {
    const sale = await this.prisma.sale.findUnique({
      where: { id },
      include: {
        customer: { select: { id: true, name: true, shopName: true, phone: true, area: true, type: true, creditLimit: true } },
        location: { select: { name: true, type: true } },
        salesman: { select: { id: true, name: true } },
        items: { include: { product: { select: { name: true, size: true } } } },
        returns: { include: { product: { select: { name: true, size: true } } } },
        payments: { select: { id: true, receiptNo: true, amount: true, method: true, status: true } },
      },
    });
    if (!sale) throw new NotFoundException();
    const limit = sale.customer?.creditLimit ?? null;
    return { ...sale, availableCredit: limit ? limit.minus(sale.newBalance) : null };
  }
}
